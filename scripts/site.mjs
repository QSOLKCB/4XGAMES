import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
const root = path.resolve(import.meta.dirname, '..');
export async function inventory() {
  const files = ['index.html', 'style.css', 'icon.svg', 'manifest.webmanifest', 'LICENSE', 'NOTICE', 'README.md', 'MOD_GUIDE.md', 'AGENTS.md', 'docs/assets/voidward-banner.svg'];
  async function walk(dir) {
    for (const entry of (await fs.readdir(path.join(root, dir), { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
      if (entry.name.startsWith('.')) continue;
      const name = `${dir}/${entry.name}`;
      if (entry.isDirectory()) await walk(name);
      else if (entry.isFile() && (/\.(js|txt|json|md)$/.test(name) || /\/(LICENSE|NOTICE)$/.test(name))) files.push(name);
    }
  }
  for (const dir of ['js', 'mods', 'vendor', 'docs']) await walk(dir);
  return files.sort();
}
export async function workerSource() {
  const files = await inventory(), hash = createHash('sha256');
  for (const file of files) { hash.update(file + '\0'); hash.update(await fs.readFile(path.join(root, file))); }
  const revision = hash.digest('hex').slice(0, 20);
  return `// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/site.mjs sync.\nconst PREFIX = 'voidward:' + self.registration.scope + ':';\nconst CACHE = PREFIX + '${revision}';\nconst ASSETS = ${JSON.stringify(files)};\nself.addEventListener('install', event => event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS.map(p => new URL(p, self.registration.scope).href))).then(() => self.skipWaiting())));\nself.addEventListener('activate', event => event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));\nself.addEventListener('fetch', event => {\n  const url = new URL(event.request.url);\n  if (event.request.method !== 'GET' || !url.href.startsWith(self.registration.scope)) return;\n  event.respondWith(fetch(event.request).then(response => response).catch(async () => {\n    const cache = await caches.open(CACHE);\n    return (await cache.match(event.request, {ignoreSearch:true})) || (event.request.mode === 'navigate' ? await cache.match(new URL('index.html', self.registration.scope).href) : null) || new Response('Resource unavailable offline', {status:503});\n  }));\n});\n`;
}
if (process.argv[1] === path.join(root, 'scripts/site.mjs')) {
  const command = process.argv[2];
  if (command === 'sync') { await fs.writeFile(path.join(root, 'sw.js'), await workerSource()); console.log('Offline inventory refreshed.'); }
  else if (command === 'build') {
    const target = path.resolve(process.argv[3] || path.join(root, '_site'));
    if (target === root || !path.basename(target).startsWith('_site')) throw new Error('Use an explicit _site* output directory.');
    await fs.rm(target, { recursive: true, force: true });
    for (const file of [...await inventory(), 'sw.js']) { await fs.mkdir(path.dirname(path.join(target, file)), { recursive: true }); await fs.copyFile(path.join(root, file), path.join(target, file)); }
    await fs.writeFile(path.join(target, '.nojekyll'), ''); console.log(`Staged ${target}`);
  } else throw new Error('Usage: node scripts/site.mjs sync | build [_site-directory]');
}
